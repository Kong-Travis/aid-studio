#!/usr/bin/env node
// Admin menus and dictionary labels live in the database (sys_menu, sys_dict_data), seeded by
// upstream's sql/*.sql. This script collects their Chinese labels into the catalog and turns the
// dictionary into an idempotent override script.
//
//   node vi/scripts/sql.mjs extract   writes vi/catalog/sql.json
//   node vi/scripts/sql.mjs build     writes vi/sql/vi-labels.sql (run after every upstream SQL upgrade)
import fs from 'node:fs'
import path from 'node:path'
import { REPO, readDict, stringifyClean } from './lib/dict.mjs'

const HAN = /\p{Script=Han}/u
const TARGETS = {
  sys_menu: { column: 'menu_name', index: 1 },
  sys_dict_data: { column: 'dict_label', index: 2 }
}

// Splits a SQL fragment into single-quoted literals and bare tokens.
function tokens(sql) {
  const out = []
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i]
    if (c === "'") {
      let s = ''
      for (i++; i < sql.length; i++) {
        if (sql[i] === '\\') { s += sql[++i]; continue }
        if (sql[i] === "'" && sql[i + 1] === "'") { s += "'"; i++; continue }
        if (sql[i] === "'") break
        s += sql[i]
      }
      out.push({ str: s })
    } else if (/[(),;]/.test(c)) {
      out.push({ punct: c })
    } else if (!/\s/.test(c)) {
      let s = c
      while (i + 1 < sql.length && !/[\s(),;']/.test(sql[i + 1])) s += sql[++i]
      out.push({ word: s })
    }
  }
  return out
}

function extractLabels(sql) {
  const found = {}
  const re = /INSERT\s+INTO\s+`?(sys_menu|sys_dict_data)`?\s*(\(([^)]*)\))?\s*(VALUES|SELECT)/gi
  let m
  while ((m = re.exec(sql))) {
    const table = m[1].toLowerCase()
    const { column, index } = TARGETS[table]
    const cols = m[3]?.split(',').map((c) => c.trim().replace(/`/g, ''))
    const col = cols ? cols.indexOf(column) : index
    if (col < 0) continue
    const end = sql.indexOf(';', re.lastIndex)
    const toks = tokens(sql.slice(re.lastIndex, end < 0 ? undefined : end))
    // Walk each top-level tuple (VALUES) or the single SELECT list, counting fields by commas.
    let depth = m[4].toUpperCase() === 'SELECT' ? 1 : 0
    let field = 0
    for (const t of toks) {
      if (t.punct === '(') { depth++; if (depth === 1) field = 0; continue }
      if (t.punct === ')') { depth--; continue }
      if (t.punct === ',' && depth === 1) { field++; continue }
      if (t.word && /^(FROM|WHERE)$/i.test(t.word) && depth === 1) break
      if (depth === 1 && field === col && t.str != null && HAN.test(t.str)) (found[t.str] ??= new Set()).add(table)
    }
  }
  return found
}

const cmd = process.argv[2]
if (cmd === 'extract') {
  const all = {}
  const dir = path.join(REPO, 'sql')
  for (const f of fs.readdirSync(dir).filter((n) => n.endsWith('.sql')).sort()) {
    for (const [label, tables] of Object.entries(extractLabels(fs.readFileSync(path.join(dir, f), 'utf8')))) {
      const e = (all[label] ??= { kind: 'sql', n: 0, files: [] })
      e.n++
      for (const t of tables) if (!e.files.includes(t)) e.files.push(t)
    }
  }
  const sorted = Object.fromEntries(Object.keys(all).sort().map((k) => [k, all[k]]))
  fs.writeFileSync(path.join(REPO, 'vi/catalog/sql.json'), stringifyClean(sorted) + '\n')
  console.log(`sql: ${Object.keys(sorted).length} menu and dictionary labels`)
} else if (cmd === 'build') {
  const dict = readDict()
  const catalog = JSON.parse(fs.readFileSync(path.join(REPO, 'vi/catalog/sql.json'), 'utf8'))
  const q = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "''") + "'"
  const lines = [
    '-- Generated by vi/scripts/sql.mjs build. Do not edit by hand.',
    '-- Renames seeded admin menus and dictionary labels to Vietnamese. Matching is by the original',
    '-- Chinese label, so running it again is a no-op. Run it after upstream\'s own upgrade SQL, then',
    '-- refresh the dictionary cache (admin: dictionary page, refresh cache) or restart the backend.',
    'SET NAMES utf8mb4;'
  ]
  let n = 0
  for (const [zh, e] of Object.entries(catalog)) {
    const vi = dict[zh]
    if (!vi) continue
    for (const table of e.files) {
      const { column } = TARGETS[table]
      lines.push(`UPDATE \`${table}\` SET \`${column}\` = ${q(vi)} WHERE \`${column}\` = ${q(zh)};`)
      n++
    }
  }
  fs.mkdirSync(path.join(REPO, 'vi/sql'), { recursive: true })
  fs.writeFileSync(path.join(REPO, 'vi/sql/vi-labels.sql'), lines.join('\n') + '\n')
  console.log(`vi/sql/vi-labels.sql: ${n} updates (${Object.keys(catalog).length - Object.keys(catalog).filter((k) => dict[k]).length} labels untranslated)`)
} else {
  console.error('usage: sql.mjs extract|build')
  process.exit(64)
}
